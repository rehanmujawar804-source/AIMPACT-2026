/**
 * ProofTrail — Evidence Brief Markdown Exporter
 * Generates an auditable, source-linked Markdown investigation brief
 * and triggers client-side download without external dependencies.
 */

import { type DisputeInput, type Finding } from "@/types";
import { formatINR, formatDate } from "./formatters";

export interface ExportBriefData {
  investigationId: string;
  dispute: DisputeInput;
  reconciliation: {
    invoice_id: string;
    buyer_name?: string;
    invoice_amount: number;
    recorded_payments: number;
    approved_credits: number;
    recorded_balance: number;
    potential_credit_amount?: number;
    disputed_quantity?: number;
    unit_price?: number;
  };
  findings: Finding[];
  nextSteps: string[];
}

export function generateEvidenceBriefMarkdown(data: ExportBriefData): string {
  const { investigationId, dispute, reconciliation, findings, nextSteps } = data;
  const now = new Date().toISOString().split("T")[0];

  return `# ProofTrail — Forensic Evidence Investigation Brief

**Investigation ID:** \`${investigationId}\`  
**Disputed Invoice:** \`${reconciliation.invoice_id}\`  
**Buyer / Counterparty:** ${reconciliation.buyer_name || "Commercial Buyer"}  
**Date of Report:** ${now}  
**Investigation Mode:** Deterministic Verification (Rules-Only Baseline)  

---

## 1. Disputed Commercial Claim

> "${dispute.message}"

* **Issue Type:** ${dispute.claimed_issue || "short_delivery"}
* **Disputed Quantity:** ${reconciliation.disputed_quantity !== undefined ? `${reconciliation.disputed_quantity} units` : "Not specified"}
* **Invoice Reference:** \`${dispute.invoice_id || reconciliation.invoice_id}\`
* **Shipment / POD Reference:** \`${dispute.shipment_id || "Not specified"}\`

---

## 2. Financial Ledger Reconciliation

| Financial Position | Amount (INR) | Verification Basis |
| :--- | :--- | :--- |
| **1. Commercial Invoice Total** | ${formatINR(reconciliation.invoice_amount)} | Verified Invoice line-item arithmetic |
| **2. Less: Recorded Payments** | -${formatINR(reconciliation.recorded_payments)} | Bank transaction confirmed & credited |
| **3. Less: Approved Credit Notes** | -${formatINR(reconciliation.approved_credits)} | Authorized issued credit notes |
| **Recorded Outstanding Balance** | **${formatINR(reconciliation.recorded_balance)}** | **Before unapproved credit adjustments** |

${
  reconciliation.potential_credit_amount
    ? `\n> [!NOTE]\n> **Buyer Requested Credit:** ${formatINR(
        reconciliation.potential_credit_amount
      )} (Disputed ${reconciliation.disputed_quantity || 0} units × ${formatINR(
        reconciliation.unit_price || 0
      )}). Under ProofTrail audit rules, unapproved requested credit is NOT subtracted from the recorded balance until an authorized credit note is issued.\n`
    : ""
}

---

## 3. Findings & Evidence Citations

${findings
  .map(
    (f, idx) => `### Finding ${idx + 1}: \`${f.finding_id}\` [${f.status}]

**Statement:** ${f.statement}

* **Status:** \`${f.status}\`
* **Source Records:** ${f.source_record_ids.map((id) => `\`${id}\``).join(", ") || "None"}
${
  f.calculation
    ? `* **Calculation:** \`${f.calculation.expression} = ${f.calculation.result} ${f.calculation.unit}\`\n`
    : ""
}${
      f.assumptions && f.assumptions.length > 0
        ? `* **Assumptions:**\n${f.assumptions.map((a) => `  - ${a}`).join("\n")}\n`
        : ""
    }${
      f.limitations && f.limitations.length > 0
        ? `* **Limitations:**\n${f.limitations.map((l) => `  - ${l}`).join("\n")}\n`
        : ""
    }${f.next_step ? `* **Next Action:** ${f.next_step}\n` : ""}`
  )
  .join("\n\n")}

---

## 4. Next Verification Steps

${
  nextSteps.length > 0
    ? nextSteps.map((step, idx) => `${idx + 1}. [ ] ${step}`).join("\n")
    : "No further verification steps pending."
}

---

## 5. Traceability & Integrity Declarations

* All financial and quantity calculations were evaluated using pure deterministic arithmetic without LLM drift.
* Absence of a record in the dataset (\`NOT_FOUND_IN_PROVIDED_DATA\`) represents missing documentation, not proof of real-world non-existence.
* This brief provides forensic documentation of transaction records; it does not issue legal verdicts or accusations of fraud.

*Report generated by ProofTrail Investigation Assistant · AIMPACT 2026*
`;
}

export function downloadEvidenceBrief(data: ExportBriefData): void {
  const markdown = generateEvidenceBriefMarkdown(data);
  const blob = new Blob([markdown], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `ProofTrail_Evidence_Brief_${data.reconciliation.invoice_id || "Case"}.md`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

